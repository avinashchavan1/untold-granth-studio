#!/usr/bin/env python3
"""Write the channel's media index into the repo, so every reel's files and live posts can be found from git alone:
  studio/series/<id>/MEDIA.md   (a readable table per reel)   +   studio/series/<id>/media.json   (the same, for scripts)
Per reel: full-quality masters (Hugging Face), the audio pack (Hugging Face, restore with scripts/audiopack.py pull <ID>),
preview / cover / citations / caption (Supabase Storage, private bucket: open them from the app's reel page), and the
live post links per platform with their dates. Run after uploads and posts (upload_reel.sh calls it).
  python3 scripts/media_index.py            write both files
  python3 scripts/media_index.py --commit   also git commit + push them when they changed
Keys are network secrets (proxy-injected); nothing secret is written."""
import json, os, subprocess, sys, urllib.parse, urllib.request
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); from channel import C, ROOT, SID, SUPA, SER, HF_MASTERS
H = {"apikey": "proxy-injected"}
APP = C.get("app_url", "").rstrip("/")
def get(q):
    return json.loads(urllib.request.urlopen(urllib.request.Request(f"{SUPA}/rest/v1/{q}", headers=H), timeout=60).read())

reels = get(f"reels?select=id,code,title,stage&series_id=eq.{SID}&order=code")
ids = ",".join(r["id"] for r in reels) or "00000000-0000-0000-0000-000000000000"
files = get(f"files?select=reel_id,kind,store,path,url,bytes,spec,created_at&reel_id=in.({ids})")
pubs = get(f"publications?select=reel_id,platform,state,post_url,posted_at,scheduled_for&reel_id=in.({ids})")
hf = set()
try:
    os.environ.setdefault("HF_TOKEN", "hf_proxyinjected000000000000000000000")
    from huggingface_hub import HfApi
    hf = set(HfApi().list_repo_files(HF_MASTERS, repo_type="dataset"))
except Exception as e:                      # index still written; audio-pack presence just isn't confirmed
    print("could not list the Hugging Face repo:", str(e)[:120])
hf_url = lambda p: f"https://huggingface.co/datasets/{HF_MASTERS}/resolve/main/{urllib.parse.quote(p)}?download=true"

out = []
for r in reels:
    fs = [f for f in files if f["reel_id"] == r["id"]]
    one = lambda k: next((f for f in fs if f["kind"] == k), None)
    masters = {}
    for k, name in (("master_instagram", "instagram_facebook"), ("master_youtube", "youtube")):
        f = one(k)
        if f: masters[name] = {"url": f.get("url") or hf_url(f["path"]), "path": f["path"], "mb": round((f.get("bytes") or 0) / 1e6), "spec": f.get("spec")}
    ap = f"{SID}/{r['code']}/{r['code']}_audio.tar.gz"
    storage = {k: one(k)["path"] for k in ("preview", "thumbnail", "citations", "caption") if one(k) and one(k)["store"] == "supabase"}
    posts = {p["platform"]: {k: p[k] for k in ("state", "post_url", "posted_at", "scheduled_for") if p.get(k)}
             for p in pubs if p["reel_id"] == r["id"] and p["state"] in ("posted", "scheduled", "posting", "failed")}
    out.append({"code": r["code"], "title": r["title"], "stage": r["stage"], "app": f"{APP}/reels/{r['code']}" if APP else None,
                "masters": masters, "audio_pack": ({"url": hf_url(ap), "path": ap} if (not hf or ap in hf) else None),
                "storage": storage, "posts": posts})
    if not (masters or storage or posts): out.pop()          # plan ideas with nothing made yet stay out of the index

ser = os.path.relpath(SER, ROOT)
json.dump({"series": SID, "hf_repo": f"https://huggingface.co/datasets/{HF_MASTERS}", "storage_bucket": "reel-media (private)",
           "reels": out}, open(os.path.join(SER, "media.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

d = lambda s: s[:10] if s else ""
L = [f"# Media index: {C.get('name', SID)}", "",
     f"Generated by `scripts/media_index.py` from the studio database (do not edit by hand; it is rewritten after every upload and post).",
     f"- Masters + audio packs: Hugging Face dataset [{HF_MASTERS}](https://huggingface.co/datasets/{HF_MASTERS}) (private: open while signed in).",
     "- Preview, cover, citations, caption: Supabase Storage bucket `reel-media` (private): open them from the reel's page in the app.",
     f"- Restore a reel's recorded audio: `python3 scripts/audiopack.py pull <ID>`. Machine-readable copy: `{ser}/media.json`.", "",
     "| Reel | Title | Stage | Masters (HF) | Audio pack | Live posts |", "|---|---|---|---|---|---|"]
for x in out:
    m = " · ".join(f"[{'IG/FB' if k.startswith('insta') else 'YT'}]({v['url']}) {v['mb']} MB" for k, v in x["masters"].items()) or "none"
    a = f"[tar.gz]({x['audio_pack']['url']})" if x["audio_pack"] else "none"
    p = " · ".join((f"[{k}]({v['post_url']}) {d(v.get('posted_at'))}" if v.get("post_url") else f"{k}: {v['state']} {d(v.get('scheduled_for'))}")
                   for k, v in sorted(x["posts"].items())) or "not posted"
    t = f"[{x['code']}]({x['app']})" if x["app"] else x["code"]
    L.append(f"| {t} | {x['title']} | {x['stage']} | {m} | {a} | {p} |")
L += ["", "## Storage paths (Supabase `reel-media`)", ""]
for x in out:
    if x["storage"]: L.append(f"- **{x['code']}**: " + " · ".join(f"{k} `{v}`" for k, v in x["storage"].items()))
open(os.path.join(SER, "MEDIA.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print(f"media index: {len(out)} reels, {sum(len(x['posts']) for x in out)} posts → {ser}/MEDIA.md")

if "--commit" in sys.argv:
    g = lambda *a: subprocess.run(["git", "-C", ROOT, *a], capture_output=True, text=True)
    g("add", f"{ser}/MEDIA.md", f"{ser}/media.json")
    if g("diff", "--cached", "--quiet").returncode:
        g("commit", "-m", "Media index: links to masters, audio packs and live posts")
        print("pushed" if g("push", "-q").returncode == 0 else "committed (push failed: push later)")
